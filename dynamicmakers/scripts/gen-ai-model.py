# Builds src/ai/mobilenet-data.js: MobileNet v1 0.25 (224) cut at its global
# average pool (256 features per image), weights quantised to uint8.
# Weights: Google, Apache License 2.0 (tensorflow/tfjs-models).
# usage: python3 scripts/gen-ai-model.py   (needs internet + numpy)
import base64, json, pathlib, urllib.request
import numpy as np
BASE = 'https://storage.googleapis.com/tfjs-models/tfjs/mobilenet_v1_0.25_224/'
get = lambda name: urllib.request.urlopen(BASE + name).read()
m = json.loads(get('model.json'))
cfg = m['modelTopology']['model_config']['config']
cut = next(i for i, l in enumerate(cfg['layers']) if l['name'] == 'global_average_pooling2d_1')
cfg['layers'] = cfg['layers'][:cut + 1]
cfg['output_layers'] = [['global_average_pooling2d_1', 0, 0]]
keep = {l['name'] for l in cfg['layers']}
specs, blobs = [], []
for g in m['weightsManifest']:
    data = b''.join(get(p) for p in g['paths'])
    off = 0
    for w in g['weights']:
        n = int(np.prod(w['shape'])) if w['shape'] else 1
        arr = np.frombuffer(data, dtype=np.float32, count=n, offset=off)
        off += n * 4
        if w['name'].split('/')[0] not in keep:
            continue
        lo, hi = float(arr.min()), float(arr.max())
        scale = (hi - lo) / 255 if hi > lo else 1.0
        blobs.append(np.clip(np.round((arr - lo) / scale), 0, 255).astype(np.uint8).tobytes())
        specs.append({'name': w['name'], 'shape': w['shape'], 'dtype': 'float32',
                      'quantization': {'dtype': 'uint8', 'scale': scale, 'min': lo}})
out = {'modelTopology': m['modelTopology'], 'weightSpecs': specs,
       'weightData': base64.b64encode(b''.join(blobs)).decode()}
dest = pathlib.Path(__file__).resolve().parent.parent / 'src/ai/mobilenet-data.js'
dest.write_text('// generated by scripts/gen-ai-model.py — MobileNet v1 0.25 (224) feature extractor, uint8-quantised.\n'
                '// Weights: Google, Apache License 2.0 (https://github.com/tensorflow/tfjs-models).\n'
                'export const MOBILENET = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(dest, dest.stat().st_size)
