# Builds src/ai/movenet-data.js (→ dist/dm-pose.js): MoveNet SinglePose Lightning v4,
# embedded so the skeleton works offline. Model: Google, Apache License 2.0.
# usage: python3 scripts/gen-pose-model.py   (needs internet)
import base64, json, pathlib, urllib.request
BASE = 'https://tfhub.dev/google/tfjs-model/movenet/singlepose/lightning/4/'
get = lambda name: urllib.request.urlopen(BASE + name + '?tfjs-format=file').read()
m = json.loads(get('model.json'))
data = b''.join(get(p) for g in m['weightsManifest'] for p in g['paths'])
art = {k: v for k, v in m.items() if k != 'weightsManifest'}
art['weightSpecs'] = [w for g in m['weightsManifest'] for w in g['weights']]
art['weightData'] = base64.b64encode(data).decode()
dest = pathlib.Path(__file__).resolve().parent.parent / 'src/ai/movenet-data.js'
dest.write_text('// generated by scripts/gen-pose-model.py — MoveNet SinglePose Lightning v4 (Google, Apache License 2.0).\n'
                '// https://www.kaggle.com/models/google/movenet  — 17 body keypoints from one 192x192 image.\n'
                'window.DMAI_POSE_MODEL = ' + json.dumps(art, separators=(',', ':')) + ';\n')
print(dest, dest.stat().st_size)
