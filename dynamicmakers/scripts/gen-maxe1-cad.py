#!/usr/bin/env python3
"""MAX-E1 physics bodies + display layout from the part assembly (scripts/maxe1_asm.py).

    python3 scripts/gen-maxe1-cad.py   ->  src/sim3d/maxe1-cad.json

Per body (zero pose, world frame, metres / kg): joint origin, mass, centre of
mass and inertia, summed over the parts that move with it (each part taken as a
solid box of its bounding box). Frame masses = STEP volume x 1.15 g/cm3; servo
and electronics masses are catalogue values. Also writes, for the 3D view, every
part's matrix in its body's frame.
"""
import json, os, re, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import maxe1_asm as A

ROOT = os.path.dirname(HERE)
meta = json.loads(re.search(r'PARTS_META = (\{.*?\});', open(f'{ROOT}/src/sim3d/parts-data.js').read()).group(1))
cad = json.load(open(f'{ROOT}/sim/cad-measurements.json'))
DENS = cad['density_g_cm3']
MASS_G = {'2XL-430': 98.0, 'XL-320': 16.7, 'CM-550': 60.0, 'EF25-F27': 110.0, 'EF25-F1': 12.39 * 1.15}
EXTRA_TORSO_G = 40.0  # screws, nuts, bushings, cables

def part_mass(p):
    if p in MASS_G: return MASS_G[p] / 1000
    return cad['parts'][p]['volume_cm3'] * DENS / 1000

# body tree (parent, joint) — joint origins from the assembly
J = A.joints()
m = lambda v: (np.asarray(v, float) / 1000).round(5)
mir = lambda v: v * np.array([1, -1, 1])
BODY_POS = {'torso': np.array([0, 0, A.BOX_C])}
for s, f in (('R', lambda v: v), ('L', mir)):
    BODY_POS[f'{s}_shoulder'] = f(J['R_shoulder_pitch'][0])
    BODY_POS[f'{s}_arm'] = f(J['R_shoulder_roll'][0])
    BODY_POS[f'{s}_hip'] = f(J['R_hip_roll'][0])
    BODY_POS[f'{s}_thigh'] = f(J['R_hip_pitch'][0])
    BODY_POS[f'{s}_knee_frame'] = f(J['R_knee_hi'][0])
    BODY_POS[f'{s}_shin'] = f(J['R_knee_lo'][0])
    BODY_POS[f'{s}_ankle_frame'] = f(J['R_ankle_pitch'][0])
    BODY_POS[f'{s}_foot'] = f(J['R_ankle_roll'][0])

# parallel bars: shown with the drive link's rotation, pinned to the body above
BARS = {'thigh_bar': ('thigh', 'hip', (A.F11_DX, -A.LEG_Y, A.HIP_PITCH + A.F11_DZ)),
        'shin_bar': ('shin', 'knee_frame', (A.F11_DX, -A.LEG_Y, A.KNEE_LO - A.F11_DZ))}

items = A.assembly()
acc = {}
visual = []
for it in items:
    p, M, body = it['part'], it['M'], it['body']
    side, rest = (body[0], body[2:]) if body[:2] in ('R_', 'L_') else (None, body)
    # mass properties: bars count with the drive link's body
    mbody = f'{side}_{BARS[rest][0]}' if rest in BARS else body
    info = meta[p] if p in meta else None
    size = np.array(info['size'] if info else [1, 1, 1]) / 1000
    c_nat = np.array(info['c'] if info else [0, 0, 0])
    R = M[:3, :3]
    com = (M[:3, :3] @ c_nat + M[:3, 3]) / 1000
    mass = part_mass(p)
    Ib = np.diag([size[1]**2 + size[2]**2, size[0]**2 + size[2]**2, size[0]**2 + size[1]**2]) * mass / 12
    a = acc.setdefault(mbody, [])
    a.append((mass, com, R @ Ib @ R.T))
    # display matrix (mm part coords -> metres) relative to the body (or the bar pivot)
    # the display meshes are centred on their bounding box (parts-data 'c'), in metres
    W = M.copy()
    W[:3, 3] = (M[:3, :3] @ c_nat + M[:3, 3])
    W[:3, 3] /= 1000
    entry = {'part': p, 'color': it['color']}
    if rest in BARS:
        rot, pivb, piv = BARS[rest]
        pivw = np.array(piv, float) if side == 'R' else mir(np.array(piv, float))
        local = W.copy()
        local[:3, 3] -= pivw / 1000
        entry.update(body=f'{side}_{rot}', pivotBody=f'{side}_{pivb}',
                     pivot=list(((pivw - BODY_POS[f'{side}_{pivb}']) / 1000).round(5)))
    else:
        local = W.copy()
        local[:3, 3] -= BODY_POS[body] / 1000
        entry['body'] = body
    entry['m'] = [round(float(x), 6) for x in local.reshape(-1)]
    visual.append(entry)

# torso extras (screws, cables) spread over the box
acc['torso'].append((EXTRA_TORSO_G / 1000, np.array([0, 0, A.BOX_C]) / 1000, np.eye(3) * 1e-5))

bodies = {}
total = 0
for b, lst in acc.items():
    M_ = sum(x[0] for x in lst)
    c = sum(x[0] * x[1] for x in lst) / M_
    I = np.zeros((3, 3))
    for mi, ci, Ii in lst:
        r = ci - c
        I += Ii + mi * (np.dot(r, r) * np.eye(3) - np.outer(r, r))
    origin = BODY_POS[b] / 1000
    bodies[b] = {'pos': list(origin.round(5)), 'mass': round(M_, 4), 'com': list((c - origin).round(5)),
                 'fullinertia': [float(f'{v:.3e}') for v in (I[0, 0], I[1, 1], I[2, 2], I[0, 1], I[0, 2], I[1, 2])]}
    total += M_

joints = {}
for k, (pt, ax) in J.items():
    joints[k] = {'pos': list(m(pt)), 'axis': [round(float(v), 4) for v in ax]}

out = {'_': 'Generated by scripts/gen-maxe1-cad.py from the part assembly (scripts/maxe1_asm.py). Metres, kilograms, zero pose.',
       'total_mass': round(total, 3),
       'dims': {'sole': [0.102, 0.064, A.SOLE_T / 1000], 'ankleRoll': A.ANKLE_ROLL / 1000,
                'box': [0.0504, 0.1077, A.BOX_H / 1000], 'armLength': round((A.F14_PIVOT + 116) / 1000, 4),
                'shoulderTilt': 15, 'legY': A.LEG_Y / 1000},
       'bodies': bodies, 'joints': joints, 'visual': visual}
json.dump(out, open(f'{ROOT}/src/sim3d/maxe1-cad.json', 'w'), indent=1)
print('total mass', round(total, 3), 'kg')
for b, v in bodies.items(): print(f'{b:16s} {v["mass"]:.3f} kg  com {v["com"]}')
