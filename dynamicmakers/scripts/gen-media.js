// Embeds the few scratch-blocks icons the editor uses as data: URIs, so the
// page needs no image files (the sandboxed web preview only allows data:/blob:
// images). Usage: node scripts/gen-media.js <scratch-blocks/media dir>
const fs = require('fs');
const path = require('path');
const dir = process.argv[2];
const FILES = [
    'green-flag.svg', 'repeat.svg', 'rotate-left.svg', 'rotate-right.svg',
    'zoom-in.svg', 'zoom-out.svg', 'zoom-reset.svg', 'delete-icon.svg', 'foldout-icon.svg',
    'resize-handle.svg', 'icons/arrow.svg', 'icons/arrow_button.svg', 'icons/remove.svg'
];
const map = {};
for (const f of FILES) {
    const svg = fs.readFileSync(path.join(dir, f), 'utf8');
    map[f] = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
}
const out = path.join(__dirname, '..', 'src', 'generated', 'media.js');
fs.writeFileSync(out, `// generated by scripts/gen-media.js — do not edit\nexport const MEDIA = ${JSON.stringify(map, null, 1)};\n`);
console.log(`embedded ${FILES.length} icons -> ${path.relative(process.cwd(), out)}`);
