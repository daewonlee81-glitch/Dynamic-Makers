#!/usr/bin/env python3
"""Low-poly display meshes of the MAX-E1 parts for the 3D view.

Input: STL files exported from the ROBOTIS STEP drawings (EF25 frames, 2XL430,
XL-320; ROBOTIS 도면 자료실). The STEP/STL files themselves stay out of the
repository; only these simplified meshes (shown, not used for physics) are kept.

    python3 scripts/gen-parts.py <stl dir> src/sim3d/parts-data.js

Each part is centred on its bounding box, simplified to about TARGET triangles,
and stored as int16 positions (0.01 mm steps) + uint16 indices, all gzip'd and
base64'd into one string. Requires: trimesh, fast-simplification, numpy.
"""
import sys, json, gzip, base64, struct
import numpy as np, trimesh, fast_simplification

PARTS = {  # name: target triangle count
    '2XL-430': 3800, 'XL-320': 1400,
    'EF25-F2': 3800, 'EF25-F3': 1400, 'EF25-F4': 3200, 'EF25-F5': 2200,
    'EF25-F7': 1600, 'EF25-F9': 1600, 'EF25-F10': 1600, 'EF25-F11': 900,
    'EF25-F12': 1900, 'EF25-F14': 1400, 'EF25-F15': 2500, 'EF25-F26': 2200, 'EF25-F27': 1600,
    'EF25-F28': 1600, 'CM-550': 2500, 'EF25-F1': 1600
}
src, out = sys.argv[1], sys.argv[2]
meta, blobs, off = {}, [], 0
for name, target in PARTS.items():
    m = trimesh.load(f'{src}/{name}.stl')
    m.merge_vertices()
    v, f = m.vertices, m.faces
    if len(f) > target:
        v, f = fast_simplification.simplify(v, f, target_reduction=1 - (target / len(f)))
    lo, hi = v.min(0), v.max(0)
    v = v - ((lo + hi) / 2)  # centred; layout 'anchor' (native mm) is relative to 'c'
    q = np.round(v * 100).astype('<i2')  # mm → 0.01 mm
    idx = f.astype('<u2')
    pb, ib = q.tobytes(), idx.tobytes()
    meta[name] = {'size': [round(float(x), 1) for x in (hi - lo)], 'c': [round(float(x), 2) for x in (lo + hi) / 2], 'nv': len(q), 'nt': len(idx), 'off': off}
    blobs += [pb, ib]
    off += len(pb) + len(ib)
    print(f'{name:9s} {len(q):5d} verts {len(idx):5d} tris  size {meta[name]["size"]}')
raw = b''.join(blobs)
gz = gzip.compress(raw, 9)
with open(out, 'w') as fo:
    fo.write('// Generated by scripts/gen-parts.py from the ROBOTIS STEP drawings (display only).\n')
    fo.write(f'export const PARTS_META = {json.dumps(meta)};\n')
    fo.write(f'export const PARTS_GZ = "{base64.b64encode(gz).decode()}";\n')
print('raw', len(raw), 'gzip', len(gz))
